#!/usr/bin/env node
import { readFile, writeFile, rename, mkdir, rm, mkdtemp, lstat } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { tmpdir } from 'node:os'
import { randomUUID } from 'node:crypto'
import { compileBundle, parseSourceJson } from 'localisync_sdk/compiler'
import { createServerClient } from 'localisync_sdk/server'
import { z } from 'zod'
import type { PreparedBundle } from 'localisync_sdk/core'

/** Emit string-literal keys, preserving names rather than inventing identifiers. */
export function generateTypes(bundle: PreparedBundle) {
  const contracts = new Map(bundle.locales.flatMap(file => file.entries.map(entry => [entry.key, entry] as const)))
  const lines = [
    '// Generated by Localisync. Do not edit.',
    "import type { LocalisyncClient } from 'localisync_sdk/core'",
    'export interface Messages {'
  ]
  for (const [key, entry] of [...contracts].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
    lines.push(
      `  ${JSON.stringify(key)}: { ${entry.parameters.map(p => `${JSON.stringify(p.name)}: ${p.type === 'number' ? 'number' : 'string'}`).join('; ')} }`
    )
  lines.push(
    '}',
    'export type TranslationKey = keyof Messages',
    'export function typedTranslations(client: LocalisyncClient) {',
    '  return <K extends TranslationKey>(key: K, ...args: keyof Messages[K] extends never ? [parameters?: Record<string, never>] : [parameters: Messages[K]]) => client.translate(key, args[0])',
    '}'
  )
  return lines.join('\n') + '\n'
}
async function main() {
  const [command, input, output] = process.argv.slice(2)
  if (!['generate', 'download'].includes(command ?? '') || !input || !output)
    throw new Error('Usage: localisync generate|download <source.json> <new-output-directory>')
  if ((await lstat(resolve(input))).size > 100 * 1024 * 1024) throw new Error('Source exceeds the input limit')
  const source: unknown = parseSourceJson(await readFile(resolve(input), 'utf8'), 100 * 1024 * 1024)
  let bundle: PreparedBundle
  if (command === 'download') {
    const config = z
      .object({
        projectId: z.string(),
        distributionId: z.string(),
        channel: z.enum(['preview', 'production']),
        addresses: z.tuple([z.string(), z.string()]),
        trustedKeys: z.record(z.string(), z.string()),
        appVersion: z.string(),
        locale: z.string(),
        preparedLocales: z.array(z.string()).optional(),
        allowDevelopmentHttp: z.boolean().optional()
      })
      .parse(source)
    const cacheDirectory = await mkdtemp(join(tmpdir(), 'localisync-generation-'))
    const baseline = compileBundle({
      version: 1,
      languages: [{ locale: config.locale, fallback: null }],
      locales: [{ locale: config.locale, entries: [] }]
    })
    const client = createServerClient({
      ...config,
      preparedLocales: config.preparedLocales ?? [],
      allowDevelopmentHttp: config.allowDevelopmentHttp ?? false,
      readKey: process.env.LOCALISYNC_READ_KEY ?? '',
      cacheDirectory,
      bundle: baseline
    })
    try {
      await client.start()
      const remote = client.getSnapshot().remote
      if (!remote || client.getStatus().error) throw new Error('No verified release')
      bundle = remote.bundle
    } finally {
      await client.dispose()
      await rm(cacheDirectory, { recursive: true, force: true })
    }
  } else bundle = compileBundle(source)
  const directory = resolve(output),
    temporary = directory + '.pending-' + randomUUID()
  try {
    await lstat(directory)
    throw new Error('The output directory already exists')
  } catch (error) {
    if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error
  }
  await mkdir(temporary, { recursive: true })
  try {
    await writeFile(
      join(temporary, 'bundle.js'),
      'export default ' + JSON.stringify(bundle).replace(/</g, '\\u003c') + '\n'
    )
    await writeFile(
      join(temporary, 'bundle.d.ts'),
      "import type { PreparedBundle } from 'localisync_sdk/core'\ndeclare const bundle: PreparedBundle\nexport default bundle\n"
    )
    await writeFile(join(temporary, 'messages.ts'), generateTypes(bundle))
    await rename(temporary, directory)
  } catch (error) {
    await rm(temporary, { recursive: true, force: true })
    throw error
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  main().catch(() => {
    console.error(
      'Localisync generation failed. Check the source schema, credentials and use an unused output directory.'
    )
    process.exitCode = 1
  })
